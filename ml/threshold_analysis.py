"""
Read-Only Decision-Threshold Analysis for EduMentor AI Student Risk Predictor.

DISCLOSURE & TRANSPARENCY:
This analysis evaluates the saved model artifact ('ml/risk_model.joblib')
strictly on the reproducible synthetic held-out test set generated by 'ml/dataset.py'.
These metrics DO NOT establish or validate predictive accuracy on real human students.

CONSTRAINTS:
- Strictly read-only analysis.
- Does not modify, retrain, or overwrite 'ml/risk_model.joblib'.
- Does not alter database records, schemas, or existing project files.
"""

import os
import sys
import hashlib
import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix

current_dir = os.path.dirname(os.path.abspath(__file__))
parent_dir = os.path.dirname(current_dir)
if parent_dir not in sys.path:
    sys.path.insert(0, parent_dir)

from ml.dataset import generate_synthetic_student_data
from ml.performance_predictor import FEATURE_NAMES, MODEL_FILE


def run_threshold_analysis(thresholds=None, n_samples=600, random_seed=42):
    """
    Evaluates risk predictor performance across varying decision thresholds
    on the reproducible held-out synthetic test set.
    """
    if thresholds is None:
        thresholds = [0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60, 0.65, 0.70]

    if not os.path.exists(MODEL_FILE):
        raise FileNotFoundError(f"Model artifact not found at {MODEL_FILE}")

    # Load model strictly read-only
    payload = joblib.load(MODEL_FILE)
    model = payload['pipeline']

    # Recreate the exact reproducible 25% held-out stratified test split (N=150)
    df = generate_synthetic_student_data(n_samples=n_samples, random_seed=random_seed)
    X = df[FEATURE_NAMES]
    y = df['needs_intervention']
    _, X_test, _, y_test = train_test_split(
        X, y, test_size=0.25, random_state=random_seed, stratify=y
    )

    # Predicted probability for class 1 (At Risk / Needs Intervention)
    y_probs = model.predict_proba(X_test)[:, 1]

    total_samples = len(y_test)
    total_on_track = int(np.sum(y_test == 0))
    total_at_risk = int(np.sum(y_test == 1))
    majority_baseline_acc = total_on_track / total_samples

    rows = []
    for t in thresholds:
        y_pred = (y_probs >= t).astype(int)

        acc = float(accuracy_score(y_test, y_pred))
        prec = float(precision_score(y_test, y_pred, zero_division=0))
        rec = float(recall_score(y_test, y_pred, zero_division=0))
        f1 = float(f1_score(y_test, y_pred, zero_division=0))

        cm = confusion_matrix(y_test, y_pred, labels=[0, 1])
        tn, fp, fn, tp = cm.ravel()

        rows.append({
            'threshold': round(t, 2),
            'accuracy': round(acc, 4),
            'precision': round(prec, 4),
            'recall': round(rec, 4),
            'f1_score': round(f1, 4),
            'tp': int(tp),
            'fp': int(fp),
            'tn': int(tn),
            'fn': int(fn),
            'pred_at_risk_count': int(tp + fp)
        })

    return {
        'total_samples': total_samples,
        'total_on_track': total_on_track,
        'total_at_risk': total_at_risk,
        'majority_baseline_acc': round(majority_baseline_acc, 4),
        'threshold_results': rows,
        'disclosures': {
            'is_synthetic': True,
            'dataset_origin': 'Synthetic benchmark generator (ml/dataset.py)',
            'real_world_applicability': (
                'These metrics are measured strictly on a synthetic benchmark dataset. '
                'They do NOT establish, validate, or claim real-world predictive performance on human students.'
            ),
            'model_artifact_status': 'Loaded read-only; ml/risk_model.joblib is unmodified.'
        }
    }


def print_threshold_report(analysis=None):
    if analysis is None:
        analysis = run_threshold_analysis()

    print("=" * 86)
    print("  EduMentor AI -- Decision-Threshold Analysis (At-Risk Class)")
    print("  Strictly Read-Only Evaluation on Reproducible Held-Out Synthetic Test Set")
    print("=" * 86)
    print(f"Total Test Samples:   {analysis['total_samples']} (On-Track: {analysis['total_on_track']}, At-Risk: {analysis['total_at_risk']})")
    print(f"Majority Baseline:    {analysis['majority_baseline_acc'] * 100:.2f}% (Predicting 0 for all)")
    print("-" * 86)
    header = (
        f"{'Threshold':>9} | {'Accuracy':>8} | {'Precision':>9} | {'Recall':>8} | "
        f"{'F1-Score':>8} | {'FN (Missed)':>11} | {'FP (False Alarm)':>16} | {'TP':>4} | {'Pred Risk':>9}"
    )
    print(header)
    print("-" * 86)

    for r in analysis['threshold_results']:
        marker = " <-- default" if r['threshold'] == 0.50 else ""
        line = (
            f"{r['threshold']:>9.2f} | {r['accuracy']*100:>7.2f}% | {r['precision']*100:>8.2f}% | "
            f"{r['recall']*100:>7.2f}% | {r['f1_score']:>8.4f} | {r['fn']:>11} | "
            f"{r['fp']:>16} | {r['tp']:>4} | {r['pred_at_risk_count']:>9}{marker}"
        )
        print(line)

    print("-" * 86)
    print("Key Trade-off Observations:")
    print("  * Lower thresholds (e.g. 0.30 - 0.40): Higher recall (catches more at-risk students),")
    print("    substantially reduces False Negatives, but increases False Positives (false alarms).")
    print("  * Higher thresholds (e.g. 0.60 - 0.70): Higher precision, fewer false alarms,")
    print("    but misses a dangerous majority of at-risk students (high False Negatives).")
    print("  * Default threshold (0.50): Misses 24 of 38 at-risk students (Recall = 36.84%).")
    print("-" * 86)
    print("Scientific Transparency Notice:")
    print(f"  {analysis['disclosures']['real_world_applicability']}")
    print("=" * 86)


if __name__ == '__main__':
    print_threshold_report()
