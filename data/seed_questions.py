def seed_question_bank(db):
    """Seed the database with initial questions, inserting any new questions idempotently."""
    from models.quiz import Question
    
    existing_texts = {q[0] for q in db.session.query(Question.question_text).all()}
    added = 0
    for q in QUESTIONS_DATA:
        if q['question_text'] not in existing_texts:
            question_obj = Question(
                learning_path=q['learning_path'],
                subject_or_category=q['subject_or_category'],
                topic=q['topic'],
                difficulty=q['difficulty'],
                target_exam=q.get('target_exam'),
                question_text=q['question_text'],
                option_a=q['option_a'],
                option_b=q['option_b'],
                option_c=q['option_c'],
                option_d=q['option_d'],
                correct_option=q['correct_option'],
                explanation=q['explanation']
            )
            db.session.add(question_obj)
            existing_texts.add(q['question_text'])
            added += 1
    if added > 0:
        db.session.commit()
        print(f"Seeded {added} new questions. Total in question bank: {len(existing_texts)}.")
    else:
        print(f"Question bank already up to date with {len(existing_texts)} questions.")
